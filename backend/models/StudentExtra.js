const mongoose = require('mongoose');

const studentExtraSchema = new mongoose.Schema({
    email: { type: String, required: true, unique: true, lowercase: true },
    section: { type: String, default: '' },
    cgpa: { type: String, default: '' },
    attendance: { type: String, default: '' },
    bloodGroup: { type: String, default: '' },
    phone: { type: String, default: '' },
    address: { type: String, default: '' },
    gender: { type: String, default: '' },
    parentName: { type: String, default: '' },
    parentPhone: { type: String, default: '' },
    fatherName: { type: String, default: '' },
    fatherPhone: { type: String, default: '' },
    fatherOccupation: { type: String, default: '' },
    fatherIncome: { type: String, default: '' },
    motherName: { type: String, default: '' },
    motherPhone: { type: String, default: '' },
    motherOccupation: { type: String, default: '' },
    motherIncome: { type: String, default: '' },
    siblings: [{ type: mongoose.Schema.Types.Mixed }],
    caste: { type: String, default: '' },
    community: { type: String, default: '' },
    sslcSchool: { type: String, default: '' },
    sslcPlace: { type: String, default: '' },
    sslcGained: { type: String, default: '' },
    sslcTotal: { type: String, default: '' },
    hscSchool: { type: String, default: '' },
    hscPlace: { type: String, default: '' },
    hscGained: { type: String, default: '' },
    hscTotal: { type: String, default: '' },
    diplomaSchool: { type: String, default: '' },
    diplomaPlace: { type: String, default: '' },
    diplomaGained: { type: String, default: '' },
    diplomaTotal: { type: String, default: '' },
    diplomaApplicable: { type: Boolean, default: false },
    currentSemester: { type: String, default: '' },
    semesterGPAs: { type: mongoose.Schema.Types.Mixed, default: {} },
    events: [{ type: mongoose.Schema.Types.Mixed }],
    internships: [{ type: mongoose.Schema.Types.Mixed }],
    publications: [{ type: mongoose.Schema.Types.Mixed }],
    certifications: { type: mongoose.Schema.Types.Mixed, default: { nptel: [], patents: [], verticals: [] } },
    leetcode: { type: String, default: '' },
    linkedin: { type: String, default: '' },
    github: { type: String, default: '' },
    notes: { type: String, default: '' },
    vertical: { type: String, default: '' },
}, { timestamps: true });

// email index handled by unique: true above

module.exports = mongoose.model('StudentExtra', studentExtraSchema);
